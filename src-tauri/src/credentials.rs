//! Passwords of saved connections, kept in the operating system's credential store.
//!
//! The store is the Secret Service (GNOME Keyring, KWallet) on Linux, the Credential
//! Manager on Windows and the Keychain on macOS, through the `keyring` crate. One entry
//! per saved connection: service "dev.tosihide.iruka", user = the profile id (a random id
//! from the frontend, never the host or user name, so that renaming a connection keeps its
//! password and deleting it leaves nothing behind that can be matched to a host).
//!
//! Iruka's own files (`localStorage`, the profile list) never hold a password; the
//! frontend asks for one here right before connecting. Every call is blocking on the
//! store's side (D-Bus round trips, a possible unlock prompt), so the commands run it on
//! a blocking thread.

use keyring::{Entry, Error};

const SERVICE: &str = "dev.tosihide.iruka";

/// Profile ids are generated by the frontend (UUIDs or a time-based token); anything else
/// is refused so that the store is never asked for arbitrary keys.
fn entry(profile_id: &str) -> Result<Entry, String> {
    if profile_id.is_empty()
        || profile_id.len() > 64
        || !profile_id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-')
    {
        return Err("invalid profile id".to_string());
    }
    Entry::new(SERVICE, profile_id).map_err(|e| format!("credential store unavailable: {e}"))
}

async fn blocking<T: Send + 'static>(
    f: impl FnOnce() -> Result<T, String> + Send + 'static,
) -> Result<T, String> {
    tauri::async_runtime::spawn_blocking(f)
        .await
        .map_err(|e| format!("credential task failed: {e}"))?
}

/// Store (or replace) the password of a saved connection.
#[tauri::command]
pub async fn credential_set(profile_id: String, password: String) -> Result<(), String> {
    blocking(move || {
        entry(&profile_id)?
            .set_password(&password)
            .map_err(|e| format!("could not store the password: {e}"))
    })
    .await
}

/// The stored password of a saved connection, or None when there is none.
#[tauri::command]
pub async fn credential_get(profile_id: String) -> Result<Option<String>, String> {
    blocking(move || match entry(&profile_id)?.get_password() {
        Ok(password) => Ok(Some(password)),
        Err(Error::NoEntry) => Ok(None),
        Err(e) => Err(format!("could not read the password: {e}")),
    })
    .await
}

/// Forget the stored password of a saved connection (no error when there is none).
#[tauri::command]
pub async fn credential_delete(profile_id: String) -> Result<(), String> {
    blocking(move || match entry(&profile_id)?.delete_credential() {
        Ok(()) | Err(Error::NoEntry) => Ok(()),
        Err(e) => Err(format!("could not delete the password: {e}")),
    })
    .await
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn refuses_odd_profile_ids() {
        assert!(entry("").is_err());
        assert!(entry("host name").is_err());
        assert!(entry("a/b").is_err());
    }

    /// Needs a real credential store (an unlocked keyring in a desktop session), so it is
    /// ignored by default: `cargo test -- --ignored credentials`.
    #[test]
    #[ignore]
    fn round_trip_in_the_real_store() {
        let id = format!("test-{}", std::process::id());
        let e = entry(&id).unwrap();
        assert!(matches!(e.get_password(), Err(Error::NoEntry)));
        e.set_password("s3cret").unwrap();
        assert_eq!(e.get_password().unwrap(), "s3cret");
        e.set_password("changed").unwrap();
        assert_eq!(e.get_password().unwrap(), "changed");
        e.delete_credential().unwrap();
        assert!(matches!(e.get_password(), Err(Error::NoEntry)));
    }
}
